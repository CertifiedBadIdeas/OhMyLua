#[test]
fn emits_readable_deterministic_lua54() {
    let source = emit_lua54(&constant_program(7), &LuaBackendProfile::lua54()).unwrap();
    assert_eq!(
        source,
        concat!(
            "-- Generated by OMLua for Lua 5.4.\n",
            "\n",
            "local f0\n",
            "\n",
            "f0 = function()\n",
            "  local v0\n",
            "  goto bb0\n",
            "\n",
            "  ::bb0::\n",
            "  do\n",
            "    v0 = 7\n",
            "    return v0\n",
            "  end\n",
            "end\n",
            "\n",
            "return f0()\n",
        )
    );
}

#[test]
fn rejects_an_invalid_local_reference_before_emission() {
    let mut program = constant_program(7);
    program.functions[0].blocks[0].terminator = LirTerminator::Return {
        value: Some(local(99)),
    };
    let error = emit_lua54(&program, &LuaBackendProfile::lua54()).unwrap_err();
    assert_eq!(
        error.to_string(),
        "error[OMLUA0003]: function f0, block bb0 references missing local v99"
    );
}

#[test]
fn rejects_entry_parameters_and_lua54_local_limit_overflow() {
    let mut parameterized = constant_program(7);
    parameterized.functions[0]
        .locals
        .push(local_definition(1, LirValueKind::Integer, true));
    parameterized.functions[0].parameters.push(local_id(1));
    assert_eq!(
        emit_lua54(&parameterized, &LuaBackendProfile::lua54())
            .unwrap_err()
            .to_string(),
        "error[OMLUA0003]: entry function f0 must not have parameters"
    );

    let mut too_many_locals = constant_program(7);
    for id in 1..=200 {
        too_many_locals.functions[0].locals.push(local_definition(
            id,
            LirValueKind::Integer,
            false,
        ));
    }
    assert_eq!(
        emit_lua54(&too_many_locals, &LuaBackendProfile::lua54())
            .unwrap_err()
            .to_string(),
        "error[OMLUA0003]: function f0 declares more than 200 local names"
    );
}

