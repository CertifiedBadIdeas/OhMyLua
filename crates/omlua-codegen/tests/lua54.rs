fn constant_program(value: i64) -> LirProgram {
    program(vec![function(
        0,
        vec![local_definition(0, LirValueKind::Integer, false)],
        Vec::new(),
        Some(0),
        vec![LirBlock {
            id: block_id(0),
            statements: vec![assign(0, integer(value))],
            terminator: LirTerminator::Return {
                value: Some(local(0)),
            },
        }],
    )])
}

fn helper_program(helper: RuntimeHelper) -> LirProgram {
    let helpers = match helper {
        RuntimeHelper::I32DivTrunc => vec![RuntimeHelper::I32DivTrunc],
        RuntimeHelper::I32Rem => vec![RuntimeHelper::I32DivTrunc, RuntimeHelper::I32Rem],
    };
    let mut program = program(vec![function(
        0,
        vec![local_definition(0, LirValueKind::Integer, false)],
        Vec::new(),
        Some(0),
        vec![LirBlock {
            id: block_id(0),
            statements: vec![assign(
                0,
                LirExpression::RuntimeCall {
                    helper,
                    arguments: vec![integer(-7), integer(3)],
                },
            )],
            terminator: LirTerminator::Return {
                value: Some(local(0)),
            },
        }],
    )]);
    program.helpers = helpers;
    program
}

fn call_and_branch_program() -> LirProgram {
    let entry = function(
        0,
        vec![
            local_definition(0, LirValueKind::Integer, false),
            local_definition(1, LirValueKind::Integer, false),
            local_definition(2, LirValueKind::Bool, false),
        ],
        Vec::new(),
        Some(0),
        vec![
            LirBlock {
                id: block_id(0),
                statements: vec![
                    assign(1, integer(41)),
                    assign(
                        2,
                        LirExpression::Binary {
                            op: LirBinaryOp::Eq,
                            left: Box::new(local(1)),
                            right: Box::new(integer(41)),
                        },
                    ),
                ],
                terminator: LirTerminator::Branch {
                    condition: local(2),
                    if_true: block_id(1),
                    if_false: block_id(2),
                },
            },
            LirBlock {
                id: block_id(1),
                statements: Vec::new(),
                terminator: LirTerminator::Call {
                    callee: function_id(1),
                    arguments: vec![local(1)],
                    destination: Some(local_id(0)),
                    target: block_id(3),
                },
            },
            LirBlock {
                id: block_id(2),
                statements: vec![assign(0, integer(0))],
                terminator: LirTerminator::Jump {
                    target: block_id(3),
                },
            },
            LirBlock {
                id: block_id(3),
                statements: Vec::new(),
                terminator: LirTerminator::Return {
                    value: Some(local(0)),
                },
            },
        ],
    );
    let add_one = function(
        1,
        vec![
            local_definition(0, LirValueKind::Integer, false),
            local_definition(1, LirValueKind::Integer, true),
        ],
        vec![local_id(1)],
        Some(0),
        vec![LirBlock {
            id: block_id(0),
            statements: vec![assign(
                0,
                LirExpression::Binary {
                    op: LirBinaryOp::Add,
                    left: Box::new(local(1)),
                    right: Box::new(integer(1)),
                },
            )],
            terminator: LirTerminator::Return {
                value: Some(local(0)),
            },
        }],
    );
    program(vec![entry, add_one])
}

fn failure_program(terminator: LirTerminator) -> LirProgram {
    program(vec![function(
        0,
        Vec::new(),
        Vec::new(),
        None,
        vec![LirBlock {
            id: block_id(0),
            statements: Vec::new(),
            terminator,
        }],
    )])
}

fn program(functions: Vec<LirFunction>) -> LirProgram {
    LirProgram {
        entry: function_id(0),
        requirements: BackendRequirements {
            minimum_integer_bits: 64,
            label_jumps: true,
            native_bitwise: false,
        },
        helpers: Vec::new(),
        functions,
    }
}

fn function(
    id: u32,
    locals: Vec<LirLocal>,
    parameters: Vec<LirLocalId>,
    return_local: Option<u32>,
    blocks: Vec<LirBlock>,
) -> LirFunction {
    LirFunction {
        id: function_id(id),
        entry: block_id(0),
        parameters,
        return_local: return_local.map(local_id),
        locals,
        blocks,
    }
}

fn local_definition(id: u32, kind: LirValueKind, parameter: bool) -> LirLocal {
    LirLocal {
        id: local_id(id),
        kind,
        parameter,
    }
}

fn assign(destination: u32, value: LirExpression) -> LirStatement {
    LirStatement::Assign {
        destination: local_id(destination),
        value,
    }
}

fn local(id: u32) -> LirExpression {
    LirExpression::Value(LirValue::Local(local_id(id)))
}

fn integer(value: i64) -> LirExpression {
    LirExpression::Value(LirValue::Integer(value))
}

fn function_id(id: u32) -> LirFunctionId {
    LirFunctionId::new(id)
}

fn local_id(id: u32) -> LirLocalId {
    LirLocalId::new(id)
}

fn block_id(id: u32) -> LirBlockId {
    LirBlockId::new(id)
}

fn assert_success(program: &LirProgram, expected_stdout: &str) {
    let output = execute(program);
    assert!(
        output.status.success(),
        "Lua failed:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert_eq!(String::from_utf8(output.stdout).unwrap(), expected_stdout);
    assert!(output.stderr.is_empty());
}

fn assert_omir_success(program: &OmProgram, expected_stdout: &str) {
    let profile = LuaBackendProfile::lua54();
    let lir = lower_program(program, &profile).unwrap();
    assert_success(&lir, expected_stdout);
}

fn assert_failure(program: &LirProgram, expected_stderr: &str) {
    let output = execute(program);
    assert!(!output.status.success());
    assert!(output.stdout.is_empty());
    let stderr = String::from_utf8(output.stderr).unwrap();
    assert!(
        stderr.contains(expected_stderr),
        "unexpected stderr: {stderr}"
    );
}

fn assert_omir_failure(program: &OmProgram, expected_stderr: &str) {
    let profile = LuaBackendProfile::lua54();
    let lir = lower_program(program, &profile).unwrap();
    assert_failure(&lir, expected_stderr);
}

fn execute(program: &LirProgram) -> std::process::Output {
    use std::{
        fs,
        process::Command,
        sync::atomic::{AtomicU64, Ordering},
    };

    static NEXT_DIRECTORY: AtomicU64 = AtomicU64::new(0);
    let directory = std::env::temp_dir().join(format!(
        "omlua-lua54-{}-{}",
        std::process::id(),
        NEXT_DIRECTORY.fetch_add(1, Ordering::Relaxed)
    ));
    fs::create_dir(&directory).unwrap();
    let program_path = directory.join("program.lua");
    let source = emit_lua54(program, &LuaBackendProfile::lua54()).unwrap();
    fs::write(&program_path, source).unwrap();

    let runner = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("tests/lua54/run_and_print.lua");
    let version = Command::new("lua")
        .arg("-v")
        .output()
        .expect("Lua 5.4.8 is required on PATH");
    assert!(version.status.success());
    let version_text = format!(
        "{}{}",
        String::from_utf8_lossy(&version.stdout),
        String::from_utf8_lossy(&version.stderr)
    );
    assert!(version_text.starts_with("Lua 5.4.8 "), "{version_text}");

    let output = Command::new("lua")
        .arg(runner)
        .arg(&program_path)
        .output()
        .unwrap();
    fs::remove_dir_all(directory).unwrap();
    output
}
